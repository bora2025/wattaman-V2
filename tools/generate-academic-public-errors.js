#!/usr/bin/env node
'use strict';

// Generates plugins/wattanam.academic-management/backend/public-errors-table.js from the plugin's own
// `throw new Error('…')` / `throw new Error(`…${x}…`)` messages, so they can be declared in each route's
// error contract (see backend/public-errors.js).  `--check` fails when the table is out of date.
const fs = require('node:fs');
const path = require('node:path');
const crypto = require('node:crypto');

const backend = path.resolve(__dirname, '..', 'plugins', 'wattanam.academic-management', 'backend');
const target = path.join(backend, 'public-errors-table.js');

function sourceMessages() {
  const statics = new Set();
  const templates = new Set();
  for (const file of fs.readdirSync(backend).filter((f) => f.endsWith('.js') && !f.startsWith('public-errors')).sort()) {
    const text = fs.readFileSync(path.join(backend, file), 'utf8');
    for (const match of text.matchAll(/throw new Error\('((?:[^'\\]|\\.)+)'\)/g)) statics.add(match[1].replace(/\\'/g, "'"));
    for (const match of text.matchAll(/throw new Error\("((?:[^"\\]|\\.)+)"\)/g)) statics.add(match[1].replace(/\\"/g, '"'));
    for (const match of text.matchAll(/throw new Error\(`((?:[^`\\]|\\.)+)`\)/g)) {
      if (match[1].includes('${')) templates.add(match[1]); else statics.add(match[1]);
    }
  }
  return { statics: [...statics].sort(), templates: [...templates].sort() };
}

function statusOf(message) {
  if (/not found/i.test(message)) return 404;
  if (/access is required|not assigned|not authorized|cannot access|^Only an? |only an administrator|is not allowed|cannot (?:scan|manage)|This role/i.test(message)) return 403;
  if (/already (?:exists|registered|used|taken|enrolled)|duplicate/i.test(message)) return 409;
  return 400;
}

function codeOf(text, used) {
  let slug = text.replace(/\$\{[^}]*\}/g, 'X').toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');
  if (!/^[A-Z]/.test(slug)) slug = 'E_' + slug;
  if (slug.length < 3) slug = 'E_' + crypto.createHash('sha1').update(text).digest('hex').slice(0, 10).toUpperCase();
  slug = slug.slice(0, 56).replace(/_+$/, '');
  let code = slug, n = 2;
  while (used.has(code)) code = `${slug}_${n++}`;
  used.add(code);
  return code;
}

function escapeRegExp(text) { return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&'); }

function build() {
  const { statics, templates } = sourceMessages();
  const used = new Set();
  const STATIC = {}, ERRORS = {}, PATTERNS = [];
  for (const message of statics) {
    const code = codeOf(message, used);
    STATIC[message] = code;
    ERRORS[code] = { status: statusOf(message), message };
  }
  for (const template of templates) {
    const code = codeOf(template, used);
    const parts = template.split(/\$\{[^}]*\}/);
    PATTERNS.push(['^' + parts.map(escapeRegExp).join('(.+?)') + '$', code]);
    // The wording without the values; a core that supports `detail` shows the exact message.
    const wording = template.replace(/\$\{[^}]*\}/g, '…').replace(/\s+/g, ' ').trim();
    ERRORS[code] = { status: statusOf(template), message: wording, detail: true };
  }
  return '\'use strict\';\n\n'
    + '// GENERATED by tools/generate-academic-public-errors.js from this plugin\'s error messages. Do not edit.\n'
    + `const STATIC = ${JSON.stringify(STATIC, null, 2)};\n\n`
    + `const PATTERNS = ${JSON.stringify(PATTERNS, null, 2)};\n\n`
    + `const ERRORS = ${JSON.stringify(ERRORS, null, 2)};\n\n`
    + 'module.exports = { STATIC, PATTERNS, ERRORS };\n';
}

const next = build();
if (process.argv.includes('--check')) {
  const current = fs.existsSync(target) ? fs.readFileSync(target, 'utf8').replace(/\r\n/g, '\n') : '';
  if (current !== next) { console.error('public-errors-table.js is out of date: run node tools/generate-academic-public-errors.js'); process.exit(1); }
  console.log('public-errors-table.js is up to date');
} else {
  fs.writeFileSync(target, next);
  const table = require(target);
  console.log(`wrote ${Object.keys(table.STATIC).length} messages and ${table.PATTERNS.length} patterns`);
}
